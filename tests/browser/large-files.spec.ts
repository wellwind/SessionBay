import { expect, test } from '@playwright/test';
test('large files use bounded requests, opt-in and ranges with cancellable reads', async ({ page }, info) => {
  test.setTimeout(120000);
  const errors: string[] = [];
  await page.route('**/favicon.ico', route => route.fulfill({ status: 204 }));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/tests/browser/workspace-focus-mode.html?large-files=1');
  await expect(page.locator('[data-app-shell]')).toHaveAttribute('data-backend-ready', 'true');
  await page.getByRole('button', { name: '開啟工作區 Synthetic focus Focus shell', exact: true }).click();
  await page.locator('.xterm-screen').evaluate(node => { (window as unknown as { terminalIdentity: Element }).terminalIdentity = node; });
  await page.getByRole('button', { name: 'Files', exact: true }).click();
  await page.getByRole('button', { name: 'medium.txt', exact: true }).dblclick();
  await expect(page.getByLabel('唯讀內容：medium.txt').locator('.view-line').first()).toBeVisible();
  await page.getByRole('button', { name: 'big.txt', exact: true }).dblclick();
  await expect(page.getByText('開啟大型文字檔', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => (window as unknown as { focusFixture: { calls: { command: string; path?: string }[] } }).focusFixture.calls.filter(c => c.command === 'read_workspace_file_chunk' && c.path === 'big.txt').length)).toBe(0);
  await page.getByRole('button', { name: '繼續開啟', exact: true }).click();
  await expect(page.getByLabel('唯讀內容：big.txt').locator('.view-line').first()).toBeVisible({ timeout: 60000 });
  await expect(page.getByText('唯讀 · 純文字（效能模式）')).toBeVisible();
  await expect(page.getByRole('button', { name: '複製檔案全文' })).toBeVisible();
  await page.getByRole('button', { name: 'huge.txt', exact: true }).dblclick();
  await expect(page.getByText('分段閱讀大型文字檔', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '分段閱讀', exact: true }).click();
  await expect(page.getByLabel('檔案閱讀區段')).toContainText('1,048,576');
  await expect(page.getByRole('button', { name: '複製目前區段' })).toBeVisible();
  await page.getByRole('button', { name: '下一段', exact: true }).click();
  await expect(page.getByLabel('檔案閱讀區段')).toContainText('2,097,152');
  await page.getByRole('button', { name: 'slow.txt', exact: true }).dblclick();
  const readCount = () => page.evaluate(() => (window as unknown as { focusFixture: { calls: { command: string; path?: string }[] } }).focusFixture.calls.filter(c => c.command === 'read_workspace_file_chunk' && c.path === 'slow.txt').length);
  await expect.poll(readCount).toBeGreaterThan(0);
  await page.getByRole('button', { name: '取消讀取' }).click();
  await expect(page.getByText('已取消讀取')).toBeVisible();
  const cancelledAt = await readCount(); await page.waitForTimeout(250); expect(await readCount()).toBe(cancelledAt);
  expect(await page.evaluate(() => (window as unknown as { focusFixture: { calls: { command: string; maxBytes?: number }[] } }).focusFixture.calls.filter(c => c.command === 'read_workspace_file_chunk').every(c => c.maxBytes! <= 256 * 1024))).toBe(true);
  await page.locator('.workspace-tab-select').click();
  expect(await page.locator('.xterm-screen').evaluate(node => node === (window as unknown as { terminalIdentity: Element }).terminalIdentity)).toBe(true);
  expect(errors).toEqual([]); await page.screenshot({ path: info.outputPath('large-files.png') });
});
